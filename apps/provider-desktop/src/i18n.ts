export const STRINGS: Record<Lang, Strings> = { 'pt-BR': ptBR, 'pt-PT': ptPT, en, es, fr, de, it, ja, zh, ar, hi };

/** `t(chave, vars)` no idioma dado; `{var}` ausente fica visível; reserva: pt-BR. */
export function translator(lang: Lang) {
  const d = STRINGS[lang] ?? ptBR;
  return (key: Key, vars?: Record<string, string | number>): string => {
    const s = d[key] ?? ptBR[key];
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}
