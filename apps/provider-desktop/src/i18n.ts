/**
 * Textos do processo principal (menus, bandeja, diálogos) no idioma do sistema. Os mesmos 11
 * idiomas do painel (apps/provider-panel/src/i18n); pt-BR é a referência e a reserva. O painel
 * escolhe o próprio idioma no navegador; aqui não há escolha salva: vale o idioma do sistema.
 * Sem imports relativos: os testes rodam este arquivo direto no Node (test/i18n.test.ts).
 */
export type Lang = 'pt-BR' | 'pt-PT' | 'en' | 'es' | 'fr' | 'de' | 'it' | 'ja' | 'zh' | 'ar' | 'hi';
export const LANGS: readonly Lang[] = ['pt-BR', 'pt-PT', 'en', 'es', 'fr', 'de', 'it', 'ja', 'zh', 'ar', 'hi'];
const isLang = (x: string): x is Lang => (LANGS as readonly string[]).includes(x);

/** `pt-BR`/`pt_BR` → pt-BR; `pt-PT` → pt-PT; `pt` → pt-BR; `en-GB` → en; `zh-Hans-CN` → zh; desconhecido → null. */
export function matchLang(tags: readonly string[]): Lang | null {
  for (const raw of tags) {
    const tag = (raw ?? '').trim().replace(/_/g, '-');
    if (!tag) continue;
    if (isLang(tag)) return tag;
    const lower = tag.toLowerCase();
    if (lower === 'pt-br') return 'pt-BR';
    if (lower === 'pt-pt') return 'pt-PT';
    const base = lower.split('-')[0]!;
    if (base === 'pt') return 'pt-BR';
    if (isLang(base)) return base;
  }
  return null;
}

